import { ApiProperty } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  ArrayMinSize,
  IsArray,
  IsDefined,
  IsIn,
  IsInt,
  IsISO8601,
  IsNumber,
  IsOptional,
  IsUUID,
  Min,
  ValidateIf,
  ValidateNested,
} from 'class-validator';
import {
  PLAYBACK_EVENT_TYPES,
  PLAYBACK_SOURCE_TYPES,
  PlaybackEventType,
  PlaybackSourceType,
} from '@platform/contracts';

export const MAX_EVENTS_PER_BATCH = 50;

const finite = { allowNaN: false, allowInfinity: false };

export class PlaybackSourceDto {
  @ApiProperty({ enum: PLAYBACK_SOURCE_TYPES, example: 'playlist' })
  @IsIn(PLAYBACK_SOURCE_TYPES)
  type: PlaybackSourceType;

  @ApiProperty({
    required: false,
    example: 3,
    description: 'playlist / profile id',
  })
  @IsOptional()
  @IsInt()
  @Min(1)
  id?: number;
}

export class PlaybackEventDto {
  @ApiProperty({
    description:
      'UUID generated by the client; a retried event with the same id is stored once',
    example: '3f0c5a52-7c5e-4c4d-9d6e-2b8a4f3f9e11',
  })
  @IsUUID()
  event_id: string;

  @ApiProperty({ enum: PLAYBACK_EVENT_TYPES, example: 'playback.started' })
  @IsIn(PLAYBACK_EVENT_TYPES)
  type: PlaybackEventType;

  @ApiProperty({
    description: 'client time, ISO 8601',
    example: new Date().toISOString(),
  })
  @IsISO8601({ strict: true })
  occurred_at: string;

  @ApiProperty({
    description: 'one id per listening session of a track',
    example: 'b1a7d9a0-4b8e-4c3a-8f39-0b0c7f3c2d11',
  })
  @IsUUID()
  play_id: string;

  @ApiProperty({ example: 42 })
  @IsInt()
  @Min(1)
  song_id: number;

  @ApiProperty({ example: 15.2, description: 'seconds' })
  @IsNumber(finite)
  @Min(0)
  position_sec: number;

  @ApiProperty({ required: false, nullable: true, example: 245.1 })
  @IsOptional()
  @IsNumber(finite)
  @Min(0)
  duration_sec?: number | null;

  @ApiProperty({ type: PlaybackSourceDto })
  @IsDefined()
  @ValidateNested()
  @Type(() => PlaybackSourceDto)
  source: PlaybackSourceDto;

  @ApiProperty({ required: false, description: 'playback.seeked only' })
  @ValidateIf((event) => event.type === 'playback.seeked')
  @IsNumber(finite)
  @Min(0)
  from_sec?: number;

  @ApiProperty({ required: false, description: 'playback.seeked only' })
  @ValidateIf((event) => event.type === 'playback.seeked')
  @IsNumber(finite)
  @Min(0)
  to_sec?: number;
}

export class TrackPlaybackEventsRequest {
  @ApiProperty({ type: [PlaybackEventDto] })
  @IsArray()
  @ArrayMinSize(1)
  @ArrayMaxSize(MAX_EVENTS_PER_BATCH)
  @ValidateNested({ each: true })
  @Type(() => PlaybackEventDto)
  events: PlaybackEventDto[];
}
